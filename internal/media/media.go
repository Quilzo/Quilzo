// Package media accepts files without accepting what is inside them.
//
// # The controls, and which one this gets for free
//
// OWASP names four controls that have to work together for uploads: replace the
// caller's filename with one the server generates, validate content with a
// format-specific parser rather than magic bytes, store files somewhere the web
// server will not execute them, and serve them from a separate origin.
//
// Three of those fall out of the architecture rather than being added to it.
// Content is addressed by the SHA-256 of its bytes, so the stored name is
// generated by definition and no caller-supplied string ever becomes a path —
// which retires filename traversal, null bytes, `.php.jpg`, Windows reserved
// names and case-folding collisions in one go. Storage is the same object store
// the content uses: opaque blobs, no extensions, nothing a web server would
// dispatch on.
//
// The fourth, a separate origin, cannot be given by a library. What is done
// instead is documented on Serve, and the honest summary is that the sandbox
// headers are a mitigation and a second origin is the fix.
//
// # Magic bytes are not validation
//
// A polyglot satisfies a magic-byte check and is also something else. The GIFAR
// was a GIF and a JAR; a JPEG can carry a valid ZIP after its end marker. So
// every accepted format is *decoded* here, not sniffed. An image has to parse
// as an image and report plausible dimensions. A PDF has to have a header, a
// trailer, and no construct that makes a viewer do work.
//
// # What is refused outright
//
// SVG. It is XML that browsers execute: <script> works, so do event handlers,
// external references and entity expansion, and ImageTragick showed the
// server-side half. A sanitiser for it is a permanent commitment to tracking
// every new way to say "script" in XML, and this is a CMS, not a research
// project. PNG, JPEG and WebP cover what SVG is usually used for; anything that
// truly needs SVG can go through a person who understands what they are
// pasting.
//
// HTML, JavaScript, and anything the server could be persuaded to execute, for
// the reason that needs no elaboration.
package media

