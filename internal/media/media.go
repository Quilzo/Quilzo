// Kind is a category of accepted file.
type Kind string

const (
	Image    Kind = "image"
	Video    Kind = "video"
	Audio    Kind = "audio"
	Document Kind = "document"
	Text     Kind = "text"
)

// Format is one accepted file format.
type Format struct {
	// MIME is what will be served. Taken from this table, never from the
	// upload: a caller-supplied Content-Type is a request, not a fact.
	MIME string
	Kind Kind
	// Ext is appended to download names only. It is never part of a stored
	// path, because nothing caller-influenced is.
	Ext string
	// Magic are the byte prefixes that may start this format.
	Magic [][]byte
	// MaxBytes bounds this format specifically. A 200 MB PNG is not a
	// photograph, it is a decompression bomb with a header.
	MaxBytes int64
	// Verify decodes the file properly. Returning an error refuses it.
	Verify func([]byte) error
	// Inline says the browser may render it directly. Everything else is sent
	// as an attachment, so a format this package does not fully understand
	// cannot become a page in the site's own origin.
	Inline bool
}

const (
	maxImage    = 24 << 20  // 24 MiB
	maxDocument = 64 << 20  // 64 MiB
	maxAV       = 512 << 20 // 512 MiB
	maxText     = 4 << 20   // 4 MiB
)

// MaxPixels bounds decoded image area.
//
// A 64000x64000 PNG compresses to a few kilobytes and decodes to about twelve
// gigabytes. The file-size limit does not catch it, because the file is small;
// the pixel count is the thing that has to be bounded. 50 megapixels is beyond
// any camera someone is likely to upload from.
const MaxPixels = 50_000_000

